/** 拍平后的全部表情（搜索用） */
export const ALL_EMOJIS: readonly { emoji: string; keywords: string; group: string }[] =
  EMOJI_GROUPS.flatMap((group) =>
    group.emojis.map(([emoji, keywords]) => ({ emoji, keywords, group: group.id })),
  );

/**
 * 按关键词过滤（空查询返回全部）。
 * 匹配规则：关键词字段包含查询串（不区分大小写），或用表情本身精确匹配。
 */
export function searchEmojis(query: string): string[] {
  const q = query.trim().toLowerCase();
  if (!q) return ALL_EMOJIS.map((e) => e.emoji);
  return ALL_EMOJIS.filter((e) => e.emoji === q || e.keywords.toLowerCase().includes(q)).map(
    (e) => e.emoji,
  );
}
